"""Generate the bounded public action allowlist for aggregate counters."""
from pathlib import Path
import json,re,sys
from urllib.parse import urlparse
ROOT=Path(__file__).resolve().parents[1]
def build(filenames=None):
    if filenames is None:filenames=[p['slug'] for p in json.loads((ROOT/'content/site.json').read_text(encoding='utf-8'))]+[json.loads(p.read_text(encoding='utf-8'))['slug'] for p in (ROOT/'content/pages').glob('*.json')]+[p['slug']+'.html' for p in json.loads((ROOT/'content/journal.json').read_text(encoding='utf-8'))]
    pages=['/' if p.name=='index.html' else '/'+p.stem for p in [Path(f) for f in filenames] if p.suffix=='.html' and p.name!='404.html']
    pdfs=['/'+p.relative_to(ROOT).as_posix() for p in (ROOT/'resources').rglob('*.pdf')]
    books=json.loads((ROOT/'content/books.json').read_text(encoding='utf-8'))['books']
    asins=set()
    for book in books:
        for url in [book['url']]+[f['url'] for f in book.get('formats',[])]:
            m=re.search(r'/dp/([A-Z0-9]{10})',url)
            if m:asins.add(m[1])
    ids=[v['id'] for v in json.loads((ROOT/'content/relaxation-videos.json').read_text(encoding='utf-8'))]
    result={'page_view':sorted(set(pages)),'resource_download':sorted(pdfs),'resource_preview':sorted(pdfs),'book_click':sorted(asins),'video_select':sorted(ids)}
    (ROOT/'lib').mkdir(exist_ok=True)
    path=ROOT/'lib/metric-targets.js'
    value='// Generated by scripts/build_metric_targets.py\nexport const targets = '+json.dumps(result,indent=2)+';\n'
    if not path.exists() or path.read_text()!=value:
        if '--check' in sys.argv:raise ValueError('Metric target allowlist needs rebuilding')
        path.write_text(value)
if __name__=='__main__':build()
